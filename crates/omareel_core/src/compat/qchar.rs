//! `QChar`'s Unicode rules that omareel depends on, as Qt 6.11.2 has them (Unicode 17.0).
//!
//! A `QChar` is one UTF-16 code unit, so these take a `u16`; a surrogate is a category of its own
//! (`Other_Surrogate`) with no case mapping. The tables are Qt's own answers rather than Rust's:
//! Rust's `char` methods follow whatever Unicode version the toolchain ships (Arch Linux ARM's can
//! trail Arch's), `char::is_alphanumeric` is the derived Alphabetic property rather than the
//! letter and number categories, and `char::to_uppercase` gives full mappings. They were generated
//! by asking Qt 6.11.2 for `QChar(u).toUpper()` and `QChar(u).isLetterOrNumber()` for every code
//! unit and `QString::toLower()` (see `qstring`) for every code point, and checked against those
//! answers with no differences.

/// A run of code points whose case mapping adds `delta`: `start`, `start + stride`, ... up to
/// `end`. Code points between them (when `stride` is 2) are not mapped.
pub(crate) type CaseRun = (u32, u32, i32, u32);

/// The mapping of `cp` in sorted, non-overlapping `runs`, or `cp` itself.
pub(crate) fn map_case(runs: &[CaseRun], cp: u32) -> u32 {
    let next = runs.partition_point(|run| run.0 <= cp);
    match next.checked_sub(1).map(|i| runs[i]) {
        Some((start, end, delta, stride)) if cp <= end && (cp - start) % stride == 0 => cp.wrapping_add_signed(delta),
        _ => cp,
    }
}

/// `QChar::toUpper()`: the uppercase of one code unit, or the unit itself. Qt keeps mappings to
/// more than one character (`ß` to `SS`, and `ᾀ` to `ἈΙ` even though its simple mapping is `ᾈ`) as
/// special cases that a single `QChar` cannot hold, and leaves those characters alone.
pub fn to_upper(ch: u16) -> u16 {
    // Every run in the table maps code units to code units, so the result fits.
    map_case(&UPPER, u32::from(ch)) as u16
}

/// `QChar::isLetterOrNumber()`: the code unit's general category is a letter (Lu, Ll, Lt, Lm,
/// Lo) or a number (Nd, Nl, No). Marks that Unicode counts as alphabetic (U+0345, U+0903) and
/// circled letters (U+24B6) are not.
pub fn is_letter_or_number(ch: u16) -> bool {
    let next = LETTER_OR_NUMBER.partition_point(|&(start, _)| start <= ch);
    next.checked_sub(1).is_some_and(|i| ch <= LETTER_OR_NUMBER[i].1)
}

