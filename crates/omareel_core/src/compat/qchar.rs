#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn upper_case_per_code_unit() {
        assert_eq!(to_upper(u16::from(b'a')), u16::from(b'A'));
        assert_eq!(to_upper(u16::from(b'A')), u16::from(b'A'));
        assert_eq!(to_upper(0x00FF), 0x0178); // ÿ
        assert_eq!(to_upper(0x0131), 0x0049); // dotless ı
        assert_eq!(to_upper(0x017F), 0x0053); // long ſ
        assert_eq!(to_upper(0x01C6), 0x01C4); // ǆ
        assert_eq!(to_upper(0x01C5), 0x01C4); // titlecase ǅ
        assert_eq!(to_upper(0x0101), 0x0100); // a stride-2 run
        assert_eq!(to_upper(0x0100), 0x0100);
        // Multi-character uppercase: unchanged.
        assert_eq!(to_upper(0x00DF), 0x00DF); // ß
        assert_eq!(to_upper(0x1F80), 0x1F80); // ᾀ
        assert_eq!(to_upper(0x0149), 0x0149); // ŉ
        assert_eq!(to_upper(0xD801), 0xD801);
        assert_eq!(to_upper(0xFF41), 0xFF21); // fullwidth a
        assert_eq!(to_upper(0xFFFF), 0xFFFF);
    }

    #[test]
    fn letters_and_numbers_by_category() {
        for ch in *b"aZ09" {
            assert!(is_letter_or_number(u16::from(ch)));
        }
        for ch in [b' ', b'_', b'%', b'/', 0] {
            assert!(!is_letter_or_number(u16::from(ch)));
        }
        assert!(is_letter_or_number(0x00AA)); // ª, Lo
        assert!(is_letter_or_number(0x00B2)); // ², No
        assert!(is_letter_or_number(0x00BC)); // ¼, No
        assert!(is_letter_or_number(0x2160)); // Ⅰ, Nl
        assert!(is_letter_or_number(0x4E00)); // CJK
        assert!(!is_letter_or_number(0x0345)); // Mn, Other_Alphabetic
        assert!(!is_letter_or_number(0x0903)); // Mc, Other_Alphabetic
        assert!(!is_letter_or_number(0x24B6)); // Ⓐ, So, Other_Alphabetic
        assert!(!is_letter_or_number(0xD800));
        assert!(!is_letter_or_number(0xFFFF));
    }
}
