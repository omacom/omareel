//! Turns omareel's Lucide icons (assets/icons/lucide/*.svg) into `rune::Icon`s: Rune's icons are
//! the elements inside a square viewBox, so the `<svg>` root's stroke attributes move onto each
//! element.

use std::fmt::Write;
use std::path::Path;

fn main() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../assets/icons/lucide");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut names: Vec<_> = std::fs::read_dir(&dir).expect("lucide icons").filter_map(|e| e.ok()).map(|e| e.path()).filter(|p| p.extension().is_some_and(|x| x == "svg")).collect();
    names.sort();
    let mut out = String::from("// Generated by build.rs from assets/icons/lucide.\n");
    let mut table = String::from("/// An icon by its Lucide file name (\"play\", \"zoom-in\", ...).\npub fn named(name: &str) -> Option<&'static rune::Icon> {\n    match name.trim_end_matches(\".svg\") {\n");
    for path in names {
        let name = path.file_stem().unwrap().to_string_lossy().into_owned();
        let svg = std::fs::read_to_string(&path).unwrap();
        let inner_start = svg.find("<svg").and_then(|i| svg[i..].find('>').map(|j| i + j + 1)).unwrap();
        let inner_end = svg.rfind("</svg>").unwrap();
        let attrs = r#" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round""#;
        let mut body = String::new();
        for element in svg[inner_start..inner_end].split('<').skip(1) {
            let element = element.trim();
            if element.is_empty() || element.starts_with('!') {
                continue;
            }
            let element = element.trim_end_matches("/>").trim_end_matches('>').trim();
            let (tag, rest) = element.split_once(char::is_whitespace).unwrap_or((element, ""));
            write!(body, "<{tag}{attrs} {} />", rest.split_whitespace().collect::<Vec<_>>().join(" ")).unwrap();
        }
        let ident = name.to_uppercase().replace('-', "_");
        writeln!(out, "pub static {ident}: rune::Icon = rune::Icon {{ name: \"lucide-{name}\", view: 24.0, body: {body:?} }};").unwrap();
        writeln!(table, "        {name:?} => Some(&{ident}),").unwrap();
    }
    table.push_str("        _ => None,\n    }\n}\n");
    out.push_str(&table);
    std::fs::write(Path::new(&std::env::var("OUT_DIR").unwrap()).join("icons.rs"), out).unwrap();
}
